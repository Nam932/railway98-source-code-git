package com.vti.utils;

/**
 * Class MyMath
 *
 * Class này mô phỏng lại class Math của Java để luyện tập kiến thức về static
 * method
 */
public class MyMath {
	public static int max(int a, int b) {
		return (a > b) ? a : b;
	}

	public static int min(int a, int b) {
		return (a < b) ? a : b;
	}

	// Method sum()
	public static int sum(int a, int b) {
		return a + b;
	}
}
